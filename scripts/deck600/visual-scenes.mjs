export function sceneKey(brand, beat) {
  return `${brand}|${beat}`;
}

export function getSceneName(brand, beat, sceneIdx) {
  const key = sceneKey(brand, beat);
  const list = BEAT_SCENES[key];
  if (!list) return `镜头${sceneIdx}`;
  return list[sceneIdx - 1] ?? `镜头${sceneIdx}`;
}
