export function getSkillDemoSpec(page) {
  const spec = SKILL_DEMO_PAGES.find((p) => p.page === page);
  if (!spec) return null;
  const mod = SKILL_DEMO_MODULES.find((m) => page >= m.start && page <= m.end);
  return {
    ...spec,
    _meta: {
      act: 'Demo',
      modTitle: mod?.title ?? 'Showcase',
      moduleId: mod?.id ?? 'intro',
    },
  };
}
