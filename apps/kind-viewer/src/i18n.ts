export type UiLang = keyof typeof UI;

export function pickTitle(entry: SlideManifestEntry, mode: LocaleMode): string {
  if (mode === 'en') return entry.titleEn;
  if (mode === 'zh') return entry.titleZh;
  return `${entry.titleEn} / ${entry.titleZh}`;
}

export function pickBriefing(entry: SlideManifestEntry, mode: LocaleMode): string {
  if (mode === 'en') return entry.briefingEn;
  if (mode === 'zh') return entry.briefingZh;
  return `${entry.briefingEn}\n\n${entry.briefingZh}`;
}
